//! The G-code index reads a slicer's plan out of a file streamed into it.
//!
//! Each file here is `PrusaSlicer`'s syntax, written out in the test so that
//! what it plans is plain beside what is asserted, and each is streamed into
//! the real builder through [`GcodeSink`] — the interface the printer port's
//! whole-file read feeds — in pieces that cut lines part-way, as a download
//! arrives. The server's journeys run the same builder over a real slice.

use core::fmt::Write as _;
use core::future::Future as _;
use core::ops::ControlFlow;
use core::pin::pin;
use core::task::{Context, Poll, Waker};

use printobserver_core::gcode_index::{Claimed, GcodeIndexes};
use printobserver_core::{GcodeIndex, IndexBuilder, PlanFact, PlannedObject, SetValue};
use printobserver_printer_api::GcodeSink as _;
use printobserver_types::PrintId;

/// Stream a file into the builder in pieces of `piece` bytes.
fn indexed_in(text: &str, piece: usize) -> GcodeIndex {
    let mut builder = IndexBuilder::new();
    for chunk in text.as_bytes().chunks(piece) {
        assert_eq!(builder.take(chunk), ControlFlow::Continue(()));
    }
    builder.finish()
}

/// Stream a file into the builder in pieces that cut its lines.
fn indexed(text: &str) -> GcodeIndex {
    indexed_in(text, 7)
}

/// The offset just past the first line carrying `needle`, which is where a
/// position has read that line.
fn past(text: &str, needle: &str) -> i64 {
    let at = text.find(needle).expect("the file carries the line");
    let end = text[at..]
        .find('\n')
        .map_or(text.len(), |newline| at + newline + 1);
    i64::try_from(end).expect("a small offset")
}

