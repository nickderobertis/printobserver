//! `filament_types` reads the material a file was sliced for from its tail.
//!
//! The file is a real `PrusaSlicer` recording from `tests/real-prints/`, held
//! by the scripted `OctoPrint` and downloaded from it over a real socket. The
//! stand-in honours a suffix `Range` as `OctoPrint`'s own file handler does and
//! counts every byte of a download it writes, so the claim that the adapter
//! reads the tail and not the file is read off what the far side served.

use core::fmt::Write as _;

use printobserver_octoprint::settings::TAIL_BYTES;
use printobserver_octoprint::standin::ScriptedOctoPrint;
use printobserver_octoprint::{OctoPrintConfig, OctoPrintPrinter};
use printobserver_printer_api::{PrinterError, PrinterPort as _};
use printobserver_types::FileName;

use crate::block_on::block_on;
use crate::stub::{Reply, Stub};

/// A recorded `PrusaSlicer` print, sliced for PLA, whose settings block is at
/// its end.
const RECORDED: &[u8] =
    include_bytes!("../../../../tests/real-prints/fan-cut-bridge/fan-cut-test.gcode");

/// A printer configured against the stand-in.
fn printer_of(standin: &ScriptedOctoPrint) -> OctoPrintPrinter {
    OctoPrintPrinter::new(
        OctoPrintConfig::new(&standin.base_url(), standin.api_key()).expect("a configuration"),
    )
}

/// A file name.
fn named(name: &str) -> FileName {
    FileName::new(name).expect("a file name")
}

/// G-code moves enough to put a settings block well past the tail's bound.
fn moves(lines: usize) -> String {
    let mut text = String::new();
    for line in 0..lines {
        writeln!(text, "G1 X{} Y{} E0.05", line % 200, line % 180)
            .expect("a String never fails to be written to");
    }
    text
}

/// The recording's material is read from its tail, and the stand-in served
/// no more of it than that tail.
#[test]
fn the_material_is_read_from_a_recorded_files_tail_without_downloading_it() {
    assert!(
        RECORDED.len() > 4 * TAIL_BYTES,
        "the recording is too short to tell a tail from the whole file"
    );
    let standin = ScriptedOctoPrint::start();
    standin.holds_file("fan-cut-test.gcode", RECORDED.to_vec(), 1_000.0);

    let types = block_on(printer_of(&standin).filament_types(named("fan-cut-test.gcode")));

    assert_eq!(types, Ok(vec![Some("PLA".to_owned())]));
    let served = standin.download_bytes();
    assert!(
        served > 0 && served <= TAIL_BYTES,
        "the stand-in served {served} bytes of a {}-byte file; the tail is {TAIL_BYTES}",
        RECORDED.len()
    );
}

/// One value per tool, in tool order, each trimmed.
#[test]
fn a_multi_tool_setting_names_each_tools_material_in_order() {
    let standin = ScriptedOctoPrint::start();
    let text = format!(
        "; generated by PrusaSlicer\n{}; prusaslicer_config = begin\n\
         ; filament_settings_id = \"a\";\"b\"\n; filament_type =  PETG ; PLA \n\
         ; printing_filament_types = PETG,PLA\n; prusaslicer_config = end\n",
        moves(20_000)
    );
    standin.holds_file("two.gcode", text.into_bytes(), 1_000.0);

    let types = block_on(printer_of(&standin).filament_types(named("two.gcode")));

    assert_eq!(
        types,
        Ok(vec![Some("PETG".to_owned()), Some("PLA".to_owned())])
    );
}

/// A file shorter than the tail is read from its first line, so a setting on
/// that line is read rather than dropped as the end of a longer one.
#[test]
fn a_file_shorter_than_the_tail_is_read_from_its_first_line() {
    let standin = ScriptedOctoPrint::start();
    standin.holds_file(
        "short.gcode",
        b"; filament_type = PETG\nG28\n".to_vec(),
        10.0,
    );

    let types = block_on(printer_of(&standin).filament_types(named("short.gcode")));

    assert_eq!(types, Ok(vec![Some("PETG".to_owned())]));
}

/// A file whose tail names no `filament_type` answers no material — and a
/// setting further up the file than the tail reaches is not read.
#[test]
fn a_file_naming_no_material_in_its_tail_answers_none() {
    let standin = ScriptedOctoPrint::start();
    let text = format!("; filament_type = PLA\n{}", moves(20_000));
    let size = text.len();
    standin.holds_file("unnamed.gcode", text.into_bytes(), 1_000.0);

    let types = block_on(printer_of(&standin).filament_types(named("unnamed.gcode")));

    assert_eq!(types, Ok(Vec::new()));
    assert!(standin.download_bytes() < size);
}

/// A file the instance does not hold is its refusal, in its own words.
#[test]
fn a_file_the_instance_does_not_hold_is_refused() {
    let standin = ScriptedOctoPrint::start();

    let types = block_on(printer_of(&standin).filament_types(named("absent.gcode")));

    assert!(
        matches!(types, Err(PrinterError::Refused { status: 404, .. })),
        "{types:?}"
    );
}

/// An instance that ignores the range and answers the whole of a long file is
/// read no further than the tail's bound and refused, rather than downloaded.
#[test]
fn an_instance_ignoring_the_range_is_refused_rather_than_read_whole() {
    let whole = format!("{}; filament_type = PLA\n", moves(20_000));
    let length = whole.len();
    let stub = Stub::start(move |request| {
        if request.path.starts_with("/downloads/") {
            Reply::Body(200, whole.clone())
        } else {
            Reply::Body(
                200,
                format!(
                    r#"{{"name": "long.gcode", "origin": "local", "type": "machinecode",
                        "size": {length},
                        "refs": {{"download": "http://ignored/downloads/files/local/long.gcode"}}}}"#
                ),
            )
        }
    });
    let printer = OctoPrintPrinter::new(
        OctoPrintConfig::new(&stub.base_url(), "test-key").expect("a configuration"),
    );

    let types = block_on(printer.filament_types(named("long.gcode")));

    assert!(
        matches!(&types, Err(PrinterError::Malformed { detail }) if detail.contains("more than the last")),
        "{types:?}"
    );
    let download = stub
        .requests()
        .into_iter()
        .find(|request| request.path.starts_with("/downloads/"))
        .expect("the download was asked for");
    assert_eq!(
        download.header("range"),
        Some(format!("bytes=-{TAIL_BYTES}").as_str())
    );
}

/// A file's facts naming a download link, as `OctoPrint` answers them.
fn facts_of(name: &str, size: usize) -> Reply {
    Reply::Body(
        200,
        format!(
            r#"{{"name": "{name}", "origin": "local", "type": "machinecode", "size": {size},
                "refs": {{"download": "http://ignored/downloads/files/local/{name}"}}}}"#
        ),
    )
}

/// A partial answer is believed only for the range it says it is: one naming
/// no range, a range that stops short of the file's end, or a body longer or
/// shorter than its range is refused rather than read as the file's tail.
#[test]
fn a_partial_answer_is_refused_unless_its_range_ends_the_file() {
    let body = "; filament_type = PLA\n";
    let length = body.len();
    for (range, sent, refusal) in [
        (None, body.to_owned(), "content ranges rather than one"),
        (
            Some(format!("bytes 100-{}/5000", 99 + length)),
            body.to_owned(),
            "no range ending a body",
        ),
        (
            Some(format!("bytes {}-4999/5000", 5000 - length - 1)),
            body.to_owned(),
            "of a range it said is",
        ),
    ] {
        let stub = Stub::start(move |request| {
            if request.path.starts_with("/downloads/") {
                let range = range
                    .as_ref()
                    .map_or_else(String::new, |range| format!("Content-Range: {range}\r\n"));
                Reply::Raw(
                    format!(
                        "HTTP/1.1 206 Partial Content\r\nContent-Length: {}\r\n{range}\
                         Connection: close\r\n\r\n{sent}",
                        sent.len()
                    )
                    .into_bytes(),
                )
            } else {
                facts_of("part.gcode", 5000)
            }
        });
        let printer = OctoPrintPrinter::new(
            OctoPrintConfig::new(&stub.base_url(), "test-key").expect("a configuration"),
        );

        let types = block_on(printer.filament_types(named("part.gcode")));

        assert!(
            matches!(&types, Err(PrinterError::Malformed { detail }) if detail.contains(refusal)),
            "{types:?}"
        );
    }
}

/// A tool the setting leaves blank is no material, and keeps its place.
#[test]
fn a_tool_the_setting_leaves_blank_names_no_material_in_its_place() {
    let standin = ScriptedOctoPrint::start();
    standin.holds_file(
        "blank.gcode",
        b"G28\n; filament_type = ;PETG\n".to_vec(),
        10.0,
    );

    let types = block_on(printer_of(&standin).filament_types(named("blank.gcode")));

    assert_eq!(types, Ok(vec![None, Some("PETG".to_owned())]));
}

/// A tail that begins part-way through a line is not read from that line,
/// however much the end of it looks like a setting.
#[test]
fn a_tail_beginning_part_way_through_a_line_does_not_read_that_line() {
    let setting = "; filament_type = ABS\n";
    let before = format!("{}G1 X1 ", moves(5_000));
    let mut after = String::from("G1 X2 E0.05\n");
    while after.len() < TAIL_BYTES - setting.len() {
        after.push_str("; padding the tail to its bound\n");
    }
    after.truncate(TAIL_BYTES - setting.len());
    let text = format!("{before}{setting}{after}");
    assert_eq!(
        text.len() - TAIL_BYTES,
        before.len(),
        "the tail begins at the `;`"
    );
    let standin = ScriptedOctoPrint::start();
    standin.holds_file("cut.gcode", text.into_bytes(), 1_000.0);

    let types = block_on(printer_of(&standin).filament_types(named("cut.gcode")));

    assert_eq!(types, Ok(Vec::new()));
}

/// Where a file names its material twice, the last setting is the one read,
/// as the settings block a slicer writes last is the one it sliced with; and
/// a setting naming nothing for any tool names no material.
#[test]
fn the_last_setting_is_read_and_a_wholly_blank_one_names_none() {
    for (text, expected) in [
        (
            "; filament_type = ABS\nG28\n; filament_type = PETG\n",
            vec![Some("PETG".to_owned())],
        ),
        ("G28\n; filament_type = \n", Vec::new()),
        ("G28\n; filament_type = ; \n", Vec::new()),
    ] {
        let standin = ScriptedOctoPrint::start();
        standin.holds_file("named.gcode", text.as_bytes().to_vec(), 10.0);

        let types = block_on(printer_of(&standin).filament_types(named("named.gcode")));

        assert_eq!(types, Ok(expected), "{text:?}");
    }
}

/// A download refused after the file's facts were read is the instance's
/// refusal, and one whose connection closes before it answers is a malformed
/// answer — neither is read as a file naming no material.
#[test]
fn a_download_refused_or_lost_after_the_facts_is_an_error() {
    for (download, refused) in [
        (
            Reply::Body(404, r#"{"error":"Not found"}"#.to_owned()),
            true,
        ),
        (Reply::Raw(Vec::new()), false),
    ] {
        let stub = Stub::start(move |request| {
            if request.path.starts_with("/downloads/") {
                download.clone()
            } else {
                facts_of("gone.gcode", 5000)
            }
        });
        let printer = OctoPrintPrinter::new(
            OctoPrintConfig::new(&stub.base_url(), "test-key").expect("a configuration"),
        );

        let types = block_on(printer.filament_types(named("gone.gcode")));

        if refused {
            assert!(
                matches!(types, Err(PrinterError::Refused { status: 404, .. })),
                "{types:?}"
            );
        } else {
            assert!(
                matches!(
                    types,
                    Err(PrinterError::Malformed { .. } | PrinterError::Unreachable { .. })
                ),
                "{types:?}"
            );
        }
    }
}
