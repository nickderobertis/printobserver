"""The three clients are one product, and two checks are what make that true.

Every journey here drives the committed check functions over a real copy of the
committed tree with one defect in it. Nothing is mocked: the drift check runs
the real generator, which runs the three real formatters, over real files.
"""

from __future__ import annotations

import json
from collections.abc import Callable
from pathlib import Path

import pytest
from repo_checks.checks_clients import (
    CLIENTS,
    client_surface,
    generated_clients,
    response_shapes,
)
from repo_checks.expect import accepted, refused, refused_naming
from treecopy import REPO_ROOT, Tree, copy_tree

RUST = "crates/printobserver-sdk/src/contract.rs"
PYTHON = "python/printobserver-sdk/src/printobserver_sdk/contract.py"
NODE = "npm/printobserver-sdk/src/contract.ts"
IMAGE_RECORD = "schemas/printobserver-types/ImageRecord.json"


@pytest.fixture
def client_tree(tmp_path: Path) -> Callable[[], Tree]:
    """A copy of the tree the client generator can be run over.

    It carries a link to the committed tree's installed JavaScript
    dependencies, because the generator lays the Node client out with the same
    `biome` the gate holds it to and that binary lives there.
    """
    counter = {"n": 0}

    def make() -> Tree:
        counter["n"] += 1
        root = copy_tree(tmp_path / f"clients{counter['n']}")
        (root / "node_modules").symlink_to(REPO_ROOT / "node_modules")
        return Tree(root)

    return make


def test_the_committed_clients_are_what_the_generator_writes(
    client_tree: Callable[[], Tree],
) -> None:
    """The tree this repository ships is accepted by the drift check."""
    accepted(generated_clients(client_tree().repo))


def test_the_committed_clients_expose_exactly_the_declared_operations(
    client_tree: Callable[[], Tree],
) -> None:
    """The tree this repository ships is accepted by the surface check."""
    accepted(client_surface(client_tree().repo))


@pytest.mark.parametrize("path", [RUST, PYTHON, NODE])
def test_a_generated_file_edited_by_hand_is_refused(
    path: str, client_tree: Callable[[], Tree]
) -> None:
    """A hand-written type agreeing today fails the moment somebody edits one."""
    broken = client_tree()
    broken.append(path, "\n// a line somebody added by hand\n")

    refused_naming(generated_clients(broken.repo), path, "a line somebody added by hand")


@pytest.mark.parametrize("path", [RUST, PYTHON, NODE])
def test_a_generated_file_that_does_not_say_it_is_generated_is_refused(
    path: str, client_tree: Callable[[], Tree]
) -> None:
    """A reader who edits one has to be told the edit will not survive."""
    broken = client_tree()
    broken.write(path, broken.read(path).replace("Generated by", "Written by", 1))

    refused_naming(generated_clients(broken.repo), path, "does not say it is generated")


def _alter(tree: Tree, alter: Callable[[dict[str, object], list[str]], None]) -> None:
    """Move one shape of a checked-in contract schema, and put it back."""
    schema = json.loads(tree.read(IMAGE_RECORD))
    properties = schema.get("properties")
    required = schema.get("required")
    if not isinstance(properties, dict) or not isinstance(required, list):
        msg = f"{IMAGE_RECORD} is not the object schema these journeys alter"
        raise AssertionError(msg)
    alter(properties, required)
    tree.write(IMAGE_RECORD, json.dumps(schema, indent=2, sort_keys=True) + "\n")


def test_a_required_field_added_to_a_schema_is_refused_naming_it(
    client_tree: Callable[[], Tree],
) -> None:
    """A field the contracts gain and the clients have not is named."""
    broken = client_tree()

    def add(properties: dict[str, object], required: list[str]) -> None:
        properties["captured_by"] = {"description": "What captured it.", "type": "string"}
        required.append("captured_by")

    _alter(broken, add)

    refused(generated_clients(broken.repo), "captured_by")


def test_a_field_renamed_in_a_schema_is_refused_naming_it(
    client_tree: Callable[[], Tree],
) -> None:
    """A rename the clients have not followed is named."""
    broken = client_tree()

    def rename(properties: dict[str, object], required: list[str]) -> None:
        properties["digest"] = properties.pop("sha256")
        required[:] = ["digest" if name == "sha256" else name for name in required]

    _alter(broken, rename)

    refused(generated_clients(broken.repo), "digest")


def test_a_fields_type_changed_in_a_schema_is_refused_naming_it(
    client_tree: Callable[[], Tree],
) -> None:
    """A field whose declared type moved is named."""
    broken = client_tree()

    def retype(properties: dict[str, object], _required: list[str]) -> None:
        properties["sha256"] = {"description": "The digest of its bytes.", "type": "number"}

    _alter(broken, retype)

