@pytest.mark.parametrize(
    ("path", "old", "new"),
    [
        (RUST, "pub fn status(", "pub fn state_of("),
        (PYTHON, "    def status(", "    def state_of("),
        (NODE, "  async status(", "  async stateOf("),
    ],
)
def test_a_client_that_renames_a_method_is_refused(
    path: str, old: str, new: str, client_tree: Callable[[], Tree]
) -> None:
    """An operation a client exposes no method for, and a method nothing backs."""
    broken = client_tree()
    broken.edit(path, old, new)

    findings = client_surface(broken.repo)
    refused(findings, "`status`, which the")
    refused(findings, "which no operation the server declares backs")


